<?php

namespace Tempest\Database\Tests\Compilers\Dialects\Postgres;

use PHPUnit\Framework\TestCase;
use Tempest\Database\Columns\IntegerColumn;
use Tempest\Database\Columns\TextColumn;
use Tempest\Database\Compilers\Dialects\Postgres\PostgresColumnCompiler;
use Tempest\Database\Compilers\Dialects\Postgres\PostgresTableCompiler;
use Tempest\Database\TableDefinitions\CreateTable;

final class PostgresTableCompilerTestCase extends TestCase
{
    public function test_compile_create_table()
    {
        $compiler = new PostgresTableCompiler(new PostgresColumnCompiler());
        $createTable = new CreateTable('users')->addColumns(
            new IntegerColumn('id')
                ->unsigned()
                ->autoIncrement()
                ->primaryKey(),
            new TextColumn('first_name'),
            new TextColumn('middle_name')->nullable(),
            new TextColumn('last_name'),
        );

        $this->assertEquals(
            <<<SQL
            CREATE TABLE "users" (
                "id" INT NOT NULL GENERATED BY DEFAULT AS IDENTITY CHECK ("id" >= 0) PRIMARY KEY,
                "first_name" TEXT NOT NULL,
                "middle_name" TEXT NULL,
                "last_name" TEXT NOT NULL
            );
            SQL,
            $compiler->compile($createTable)
        );
    }
}